#!/usr/bin/env python3
"""
make-index.py — turn the library from a blob into a map.

`library/` holds 1,824 verbatim source files. Copying them was the easy half; the hard half is
being able to answer "where does this project's material on <topic> actually come from?" without
reading 18 MB. This generates `library/INDEX.md`: for each capability the skills rely on, the
upstream files that discuss it, ranked by how much they say about it.

    python3 tools/make-index.py            # write library/INDEX.md
    python3 tools/make-index.py --check     # fail if the index is stale
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIB = ROOT / "library"

# capability -> the words that indicate it. Deliberately plain: this is a finder, not a judge.
TOPICS: dict[str, list[str]] = {
    "cutting, trims and joins": ["cut on", "trim", "j-cut", "l-cut", "j cut", "l cut", "join",
                                 "hard cut", "silence removal", "dead air"],
    "pacing and rhythm": ["pacing", "rhythm", "beat", "every 2", "every 3", "cadence", "tempo"],
    "hooks and openings": ["hook", "first second", "first three seconds", "opening", "retention"],
    "captions and subtitles": ["caption", "subtitle", "srt", "ass ", "safe zone", "karaoke"],
    "audio mix and loudness": ["lufs", "loudness", "true peak", "loudnorm", "duck", "sidechain",
                               "mix"],
    "sound effects": ["sfx", "whoosh", "riser", "impact", "swoosh", "foley", "sound design"],
    "music": ["music", "score", "bed", "track", "resolv"],
    "transitions": ["transition", "whip", "match cut", "morph", "wipe", "flash"],
    "easing, timing and springs": ["ease", "easing", "cubic-bezier", "spring", "stagger",
                                   "keyframe", "duration"],
    "animation construction": ["transform-origin", "immediateRender", "stroke-dash",
                               "gsap", "timeline", "requestAnimationFrame", "will-change"],
    "typography": ["type scale", "font", "typeface", "letter-spacing", "tracking", "baseline",
                   "line-height"],
    "colour and contrast": ["palette", "contrast", "accent", "gradient", "hue", "saturation"],
    "layout, grid and composition": ["grid", "layout", "spacing", "composition", "hierarchy",
                                     "alignment", "margin"],
    "design tokens and systems": ["token", "design system", "component", "spacing step", "radius"],
    "charts and data": ["chart", "graph", "axis", "data viz", "visualisation", "visualization"],
    "slop and anti-patterns": ["slop", "generic", "never ship", "tell of", "cliche", "cliché",
                               "banned"],
    "delivery and export": ["codec", "bitrate", "yuv420p", "container", "-crf", "export",
                            "deliver"],
    "ffmpeg technique": ["ffmpeg", "-vf", "-filter_complex", "overlay", "zoompan", "concat"],
    "transcription and asr": ["whisper", "transcri", "asr", "word timing", "phoneme"],
    "verification and review": ["verify", "measure", "audit", "gate", "checklist", "review"],
}


def scores() -> dict[str, list[tuple[int, pathlib.Path]]]:
    files = sorted(LIB.glob("*/*/upstream/**/*.md"))
    out: dict[str, list[tuple[int, pathlib.Path]]] = {t: [] for t in TOPICS}
    for f in files:
        try:
            text = f.read_text(encoding="utf-8", errors="ignore").lower()
        except OSError:
            continue
        # density, not raw count: a 2,700-line plan file mentions every topic and would win
        # every row otherwise. hits / sqrt(lines) rewards files that are *about* the topic.
        weight = max(len(text.splitlines()), 1) ** 0.5
        for topic, words in TOPICS.items():
            hits = sum(text.count(w) for w in words)
            if hits >= 2:
                out[topic].append((round(hits / weight, 2), f.relative_to(LIB)))
    for topic in out:
        out[topic].sort(key=lambda hf: (-hf[0], str(hf[1])))
    return out


def render(data: dict[str, list[tuple[int, pathlib.Path]]]) -> str:
    total = len(list(LIB.glob("*/*/upstream/**/*.md")))
    lines = [
        "# Index — where the material on each topic lives",
        "",
        "*Generated by `tools/make-index.py` from the copied sources. Do not edit by hand.*",
        "",
        f"The library holds {total:,} verbatim source files across eighteen repositories. Nobody",
        "should read them all, and no skill does. This page answers one question: **for this topic,",
        "which upstream files are worth opening?**",
        "",
        "Ranking is by mention density (mentions ÷ √lines) — a finder, not a judge. Raw counts would",
        "put one 2,700-line implementation plan at the top of every row.",
        "A file can be ranked first and still be wrong; the skills are the arbitration, and",
        "`skills/motionframe-edit/references/precedence.md` is where contradictions are settled.",
        "",
        "| Topic | Files | Start here |",
        "|---|---:|---|",
    ]
    for topic, hits in data.items():
        if not hits:
            lines.append(f"| {topic} | 0 | nothing in the copied sources |")
            continue
        best = " · ".join(f"`{p}`" for _, p in hits[:3])
        lines.append(f"| {topic} | {len(hits)} | {best} |")
    lines += [
        "",
        "## How to use it",
        "",
        "```bash",
        "grep -ril \"whoosh\" library/*/*/upstream --include=*.md | head",
        "```",
        "",
        "Open the two or three highest-ranked files for the topic, not the whole set. If a topic",
        "matters and the ranking looks wrong, fix `TOPICS` in `tools/make-index.py` — the map is",
        "generated, so it is cheap to correct.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    body = render(scores())
    target = LIB / "INDEX.md"
    if "--check" in sys.argv:
        if not target.exists():
            print("  index check FAILED — library/INDEX.md does not exist")
            return 1
        if target.read_text(encoding="utf-8") != body:
            print("  index check FAILED — library/INDEX.md is stale; run tools/make-index.py")
            return 1
        print("  index check PASS — library/INDEX.md matches the sources")
        return 0
    target.write_text(body, encoding="utf-8")
    topics = len([t for t in TOPICS])
    print(f"  wrote library/INDEX.md — {topics} topics over "
          f"{len(list(LIB.glob('*/*/upstream/**/*.md'))):,} source files")
    return 0


if __name__ == "__main__":
    sys.exit(main())

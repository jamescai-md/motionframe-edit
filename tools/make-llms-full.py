#!/usr/bin/env python3
"""
make-llms-full.py — build llms-full.txt from the skills themselves.

Single-file context dumps go stale the moment someone edits a skill, so this one is
generated from source and checked in CI: if the generated file differs from what is
committed, the build fails. Run `python3 tools/make-llms-full.py --check` locally to
see the diff without writing.
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "llms-full.txt"

ORDER = [
    "AGENTS.md",
    "skills/motionframe-edit/SKILL.md",
    "skills/motionframe-edit/references/precedence.md",
    "skills/motionframe-edit/references/craft-bar.md",
    "skills/motionframe-edit/references/glossary.md",
    "skills/motionframe-edit/references/lineage.md",
    "skills/edit-supervisor/SKILL.md",
    "skills/edit-supervisor/references/cutting.md",
    "skills/edit-supervisor/references/captions.md",
    "skills/edit-supervisor/references/sound.md",
    "skills/edit-supervisor/references/delivery.md",
    "skills/motion-director/SKILL.md",
    "skills/motion-director/references/timing.md",
    "skills/motion-director/references/reference-work.md",
    "skills/motion-director/references/transitions.md",
    "skills/motion-director/references/lanes.md",
    "skills/design-director/SKILL.md",
    "skills/design-director/references/anti-slop.md",
    "skills/design-director/references/system.md",
    "skills/ui-motion/SKILL.md",
    "skills/ui-motion/references/craft.md",
    "skills/gatekeeper/SKILL.md",
    "skills/gatekeeper/references/critic.md",
    "skills/gatekeeper/references/gates-for-design.md",
    "skills/gatekeeper/references/report-format.md",
    "skills/taste-memory/SKILL.md",
    "library/README.md",
    "specs/gates.json",
    "specs/quality-bar.md",
    "docs/plan.md",
    "docs/architecture.md",
    "docs/platforms.md",
]


def build() -> str:
    parts = [
        "# motionframe-edit — full skill context",
        "",
        "> Generated by `tools/make-llms-full.py` from the skill files. Do not edit by hand;",
        "> edit the source skill and regenerate. Single-file dump of every skill and reference",
        "> for agents with a generous context window.",
        "",
    ]
    for rel in ORDER:
        p = ROOT / rel
        if not p.exists():
            parts.append(f"<!-- missing: {rel} -->\n")
            continue
        parts.append(f"\n\n<!-- ===== {rel} ===== -->\n")
        parts.append(p.read_text(encoding="utf-8").rstrip() + "\n")
    return "".join(parts)


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("llms-full.txt is stale — run: python3 tools/make-llms-full.py")
            return 1
        print("llms-full.txt is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}  {len(text.splitlines())} lines  {OUT.stat().st_size // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
